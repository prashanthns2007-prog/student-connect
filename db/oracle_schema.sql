-- Academic ERP System: Enhanced Oracle SQL Schema with RBAC Triggers
-- This script contains all table definitions, relationships, and integrity triggers.

-- 1. Users Table (Common Authentication)
CREATE TABLE USERS (
    USER_ID VARCHAR2(50) PRIMARY KEY,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(20) NOT NULL CHECK (ROLE IN ('ADMIN', 'TEACHER', 'STUDENT', 'STAFF')),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (STATUS IN ('ACTIVE', 'DISABLED')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    LAST_LOGIN TIMESTAMP
);

-- 2. Departments
CREATE TABLE DEPARTMENTS (
    DEPT_ID VARCHAR2(20) PRIMARY KEY,
    DEPT_NAME VARCHAR2(100) NOT NULL,
    HEAD_OF_DEPT VARCHAR2(100)
);

-- 3. Courses
CREATE TABLE COURSES (
    COURSE_ID VARCHAR2(20) PRIMARY KEY,
    COURSE_NAME VARCHAR2(100) NOT NULL,
    DURATION_YEARS NUMBER(1) NOT NULL
);

-- 4. Branches
CREATE TABLE BRANCHES (
    BRANCH_ID VARCHAR2(20) PRIMARY KEY,
    COURSE_ID VARCHAR2(20) REFERENCES COURSES(COURSE_ID),
    DEPT_ID VARCHAR2(20) REFERENCES DEPARTMENTS(DEPT_ID),
    BRANCH_NAME VARCHAR2(100) NOT NULL
);

-- 5. Students
CREATE TABLE STUDENTS (
    STUDENT_ID VARCHAR2(50) PRIMARY KEY REFERENCES USERS(USER_ID),
    NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    PHONE VARCHAR2(20),
    COURSE_ID VARCHAR2(20) REFERENCES COURSES(COURSE_ID),
    BRANCH_ID VARCHAR2(20) REFERENCES BRANCHES(BRANCH_ID),
    SEMESTER NUMBER(2) NOT NULL,
    SECTION VARCHAR2(10) NOT NULL,
    ADMISSION_DATE DATE DEFAULT SYSDATE,
    REGISTRATION_NO VARCHAR2(50) UNIQUE NOT NULL
);

-- 6. Teachers
CREATE TABLE TEACHERS (
    TEACHER_ID VARCHAR2(50) PRIMARY KEY REFERENCES USERS(USER_ID),
    NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    PHONE VARCHAR2(20),
    DEPT_ID VARCHAR2(20) REFERENCES DEPARTMENTS(DEPT_ID),
    DESIGNATION VARCHAR2(100)
);

-- 7. Staff
CREATE TABLE STAFF (
    STAFF_ID VARCHAR2(50) PRIMARY KEY REFERENCES USERS(USER_ID),
    NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    ROLE_DESCRIPTION VARCHAR2(100)
);

-- 8. Subjects
CREATE TABLE SUBJECTS (
    SUBJECT_ID VARCHAR2(20) PRIMARY KEY,
    SUBJECT_NAME VARCHAR2(100) NOT NULL,
    COURSE_ID VARCHAR2(20) REFERENCES COURSES(COURSE_ID),
    BRANCH_ID VARCHAR2(20) REFERENCES BRANCHES(BRANCH_ID),
    SEMESTER NUMBER(2) NOT NULL,
    CREDITS NUMBER(2) NOT NULL
);

-- 9. Teacher Subject Assignments
CREATE TABLE TEACHER_SUBJECTS (
    ASSIGNMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TEACHER_ID VARCHAR2(50) REFERENCES TEACHERS(TEACHER_ID),
    SUBJECT_ID VARCHAR2(20) REFERENCES SUBJECTS(SUBJECT_ID),
    SECTION VARCHAR2(10) NOT NULL,
    ACADEMIC_YEAR VARCHAR2(20) NOT NULL
);

-- 10. Student Subject Enrollment
CREATE TABLE STUDENT_SUBJECTS (
    ENROLLMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENT_ID VARCHAR2(50) REFERENCES STUDENTS(STUDENT_ID),
    SUBJECT_ID VARCHAR2(20) REFERENCES SUBJECTS(SUBJECT_ID)
);

-- 11. Attendance
CREATE TABLE ATTENDANCE (
    ATTENDANCE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENT_ID VARCHAR2(50) REFERENCES STUDENTS(STUDENT_ID),
    SUBJECT_ID VARCHAR2(20) REFERENCES SUBJECTS(SUBJECT_ID),
    TEACHER_ID VARCHAR2(50) REFERENCES TEACHERS(TEACHER_ID),
    ATT_DATE DATE NOT NULL,
    STATUS VARCHAR2(10) NOT NULL CHECK (STATUS IN ('PRESENT', 'ABSENT')),
    REMARKS VARCHAR2(200)
);

-- 12. Marks
CREATE TABLE MARKS (
    MARK_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENT_ID VARCHAR2(50) REFERENCES STUDENTS(STUDENT_ID),
    SUBJECT_ID VARCHAR2(20) REFERENCES SUBJECTS(SUBJECT_ID),
    EXAM_TYPE VARCHAR2(50) NOT NULL CHECK (EXAM_TYPE IN ('INTERNAL', 'ASSIGNMENT', 'FINAL')),
    MAX_MARKS NUMBER(5, 2) NOT NULL,
    OBTAINED_MARKS NUMBER(5, 2) NOT NULL,
    TEACHER_ID VARCHAR2(50) REFERENCES TEACHERS(TEACHER_ID),
    EXAM_DATE DATE DEFAULT SYSDATE
);

-- 13. Timetable
CREATE TABLE TIMETABLE (
    ENTRY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DAY_OF_WEEK VARCHAR2(20) NOT NULL,
    START_TIME VARCHAR2(10) NOT NULL,
    END_TIME VARCHAR2(10) NOT NULL,
    SUBJECT_ID VARCHAR2(20) REFERENCES SUBJECTS(SUBJECT_ID),
    TEACHER_ID VARCHAR2(50) REFERENCES TEACHERS(TEACHER_ID),
    ROOM_NO VARCHAR2(20),
    COURSE_ID VARCHAR2(20) REFERENCES COURSES(COURSE_ID),
    BRANCH_ID VARCHAR2(20) REFERENCES BRANCHES(BRANCH_ID),
    SEMESTER NUMBER(2) NOT NULL,
    SECTION VARCHAR2(10) NOT NULL
);

-- 14. Academic Calendar
CREATE TABLE ACADEMIC_CALENDAR (
    EVENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR2(100) NOT NULL,
    EVENT_TYPE VARCHAR2(50) NOT NULL CHECK (EVENT_TYPE IN ('HOLIDAY', 'EXAM', 'EVENT', 'SEMINAR', 'IMPORTANT')),
    START_DATE DATE NOT NULL,
    END_DATE DATE,
    DESCRIPTION VARCHAR2(500)
);

-- 15. Announcements
CREATE TABLE ANNOUNCEMENTS (
    ANNOUNCEMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR2(200) NOT NULL,
    CONTENT CLOB,
    TARGET_ROLE VARCHAR2(20) DEFAULT 'ALL' CHECK (TARGET_ROLE IN ('ADMIN', 'TEACHER', 'STUDENT', 'STAFF', 'ALL')),
    CREATED_BY VARCHAR2(50) REFERENCES USERS(USER_ID),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ==========================================
-- INTEGRITY & RBAC TRIGGERS
-- ==========================================

-- Trigger 1: Ensure only 'STUDENT' users are added to STUDENTS table
CREATE OR REPLACE TRIGGER TRG_STUDENT_ROLE_CHECK
BEFORE INSERT OR UPDATE ON STUDENTS
FOR EACH ROW
DECLARE
    V_ROLE VARCHAR2(20);
BEGIN
    SELECT ROLE INTO V_ROLE FROM USERS WHERE USER_ID = :NEW.STUDENT_ID;
    IF V_ROLE != 'STUDENT' THEN
        RAISE_APPLICATION_ERROR(-20001, 'Only users with role STUDENT can be added to Students table.');
    END IF;
END;
/

-- Trigger 2: Ensure only 'TEACHER' users are added to TEACHERS table
CREATE OR REPLACE TRIGGER TRG_TEACHER_ROLE_CHECK
BEFORE INSERT OR UPDATE ON TEACHERS
FOR EACH ROW
DECLARE
    V_ROLE VARCHAR2(20);
BEGIN
    SELECT ROLE INTO V_ROLE FROM USERS WHERE USER_ID = :NEW.TEACHER_ID;
    IF V_ROLE != 'TEACHER' THEN
        RAISE_APPLICATION_ERROR(-20002, 'Only users with role TEACHER can be added to Teachers table.');
    END IF;
END;
/

-- Trigger 3: Validate Marks (Obtained <= Max)
CREATE OR REPLACE TRIGGER TRG_MARKS_VALIDATION
BEFORE INSERT OR UPDATE ON MARKS
FOR EACH ROW
BEGIN
    IF :NEW.OBTAINED_MARKS > :NEW.MAX_MARKS THEN
        RAISE_APPLICATION_ERROR(-20003, 'Obtained marks cannot exceed maximum marks.');
    END IF;
    IF :NEW.OBTAINED_MARKS < 0 THEN
        RAISE_APPLICATION_ERROR(-20004, 'Marks cannot be negative.');
    END IF;
END;
/

-- Trigger 4: Prevent Future Attendance Marking
CREATE OR REPLACE TRIGGER TRG_ATTENDANCE_DATE_CHECK
BEFORE INSERT OR UPDATE ON ATTENDANCE
FOR EACH ROW
BEGIN
    IF :NEW.ATT_DATE > SYSDATE THEN
        RAISE_APPLICATION_ERROR(-20005, 'Attendance cannot be marked for a future date.');
    END IF;
END;
/

-- Trigger 5: Ensure Students Enroll in Correct Branch Subjects
CREATE OR REPLACE TRIGGER TRG_ENROLLMENT_INTEGRITY
BEFORE INSERT ON STUDENT_SUBJECTS
FOR EACH ROW
DECLARE
    V_S_BRANCH VARCHAR2(20);
    V_SUB_BRANCH VARCHAR2(20);
BEGIN
    SELECT BRANCH_ID INTO V_S_BRANCH FROM STUDENTS WHERE STUDENT_ID = :NEW.STUDENT_ID;
    SELECT BRANCH_ID INTO V_SUB_BRANCH FROM SUBJECTS WHERE SUBJECT_ID = :NEW.SUBJECT_ID;
    
    IF V_S_BRANCH != V_SUB_BRANCH THEN
        RAISE_APPLICATION_ERROR(-20006, 'Student cannot enroll in a subject from a different branch.');
    END IF;
END;
/

